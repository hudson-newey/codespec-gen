import { readFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import * as path from "node:path";
import writeFileAtomic from "write-file-atomic";
import type {
  ArtifactMetadata,
  ArtifactManifest,
  ArtifactEntry,
} from "../../shared/src/index.js";
import {
  ArtifactManifestSchema,
  ArtifactEntrySchema,
  SCHEMA_VERSION,
} from "../../shared/src/index.js";

const MANIFEST_FILE = "manifest.json";
const LOOKUP_FILE = "lookup.json";
const PLUGIN_VERSION = "0.1.0";

/** Returns the deterministic filenames for a given cache key and block type. */
export function artifactFilenames(
  cacheKey: string,
  promptBlockType: string,
): { json: string; ts: string } {
  const base = `${cacheKey.slice(0, 16)}-${promptBlockType.replace(/[^a-zA-Z0-9_-]/g, "_")}`;
  return { json: `${base}.json`, ts: `${base}.ts` };
}

export class CacheManager {
  private cacheDir: string;
  private projectRoot: string;
  private manifest: ArtifactManifest | null = null;
  private lookup: Record<string, string> = {};
  private initialized = false;

  constructor(cacheDir: string, projectRoot: string) {
    this.cacheDir = path.resolve(cacheDir);
    this.projectRoot = path.resolve(projectRoot);
  }

  async init(): Promise<void> {
    if (this.initialized) return;
    await mkdir(this.cacheDir, { recursive: true });
    this.manifest = await this.loadManifest();
    this.lookup = await this.loadLookup();
    this.initialized = true;
  }

  /** Look up a cached generated code string by cache key. Returns null on miss. */
  async get(cacheKey: string): Promise<string | null> {
    await this.init();
    const filename = this.manifest?.[cacheKey];
    if (!filename) return null;

    const filePath = path.join(this.cacheDir, filename);
    if (!existsSync(filePath)) {
      // Manifest points to a missing file — treat as cache miss
      delete this.manifest![cacheKey];
      return null;
    }

    try {
      const raw = await readFile(filePath, "utf-8");
      const entry = ArtifactEntrySchema.safeParse(JSON.parse(raw));
      if (!entry.success) {
        // Corrupted entry — treat as miss
        delete this.manifest![cacheKey];
        return null;
      }
      return entry.data.code;
    } catch {
      return null;
    }
  }

  /** Persist a generated code artifact for a given cache key. Writes atomically. */
  async set(
    cacheKey: string,
    code: string,
    metadata: Omit<
      ArtifactMetadata,
      "pluginVersion" | "schemaVersion" | "generatedAt" | "tsFilePath"
    >,
  ): Promise<void> {
    await this.init();

    const { json: jsonFilename, ts: tsFilename } = artifactFilenames(
      cacheKey,
      metadata.promptBlockType,
    );
    const jsonPath = path.join(this.cacheDir, jsonFilename);
    const tsPath = path.join(this.cacheDir, tsFilename);
    const relTsPath = path.relative(this.projectRoot, tsPath);

    const entry: ArtifactEntry = {
      code,
      metadata: {
        ...metadata,
        pluginVersion: PLUGIN_VERSION,
        schemaVersion: SCHEMA_VERSION,
        generatedAt: new Date().toISOString(),
        tsFilePath: relTsPath,
      },
    };

    const tsContent =
      `// Generated by CodeSpec — do not edit manually\n` +
      `// Block: ${metadata.promptBlockType}\n\n` +
      `${code}\n`;

    await Promise.all([
      writeFileAtomic(jsonPath, JSON.stringify(entry, null, 2) + "\n"),
      writeFileAtomic(tsPath, tsContent),
    ]);

    this.manifest![cacheKey] = jsonFilename;
    await this.saveManifest(this.manifest!);
  }

  /**
   * Record that a source call site maps to a specific .ts artifact.
   * Call this after a cache hit or after `set()`.
   * @param sourceFilePath - Absolute path to the source file.
   * @param callStart - Character offset of the call expression start.
   * @param promptBlockType - The block type (e.g. "code$").
   * @param cacheKey - The cache key for this call site.
   */
  recordLookup(
    sourceFilePath: string,
    callStart: number,
    promptBlockType: string,
    cacheKey: string,
  ): void {
    const relSource = path.relative(this.projectRoot, sourceFilePath);
    const { ts: tsFilename } = artifactFilenames(cacheKey, promptBlockType);
    const absTs = path.join(this.cacheDir, tsFilename);
    const relTs = path.relative(this.projectRoot, absTs);
    this.lookup[`${relSource}:${callStart}`] = relTs;
  }

  /** Write the merged lookup.json to cacheDir. Call once at build end. */
  async saveLookup(): Promise<void> {
    await this.init();
    const lookupPath = path.join(this.cacheDir, LOOKUP_FILE);
    await writeFileAtomic(
      lookupPath,
      JSON.stringify(this.lookup, null, 2) + "\n",
    );
  }

  /** Remove all artifacts and reset the manifest. */
  async clear(): Promise<void> {
    await this.init();
    const entries = Object.values(this.manifest ?? {}).filter(
      (f): f is string => typeof f === "string",
    );
    await Promise.allSettled(
      entries.map(async (filename) => {
        const filePath = path.join(this.cacheDir, filename);
        if (existsSync(filePath)) {
          const { unlink } = await import("node:fs/promises");
          await unlink(filePath);
        }
      }),
    );
    this.manifest = {};
    await this.saveManifest({});
  }

  private async loadManifest(): Promise<ArtifactManifest> {
    const manifestPath = path.join(this.cacheDir, MANIFEST_FILE);
    if (!existsSync(manifestPath)) return {};
    try {
      const raw = await readFile(manifestPath, "utf-8");
      const parsed = ArtifactManifestSchema.safeParse(JSON.parse(raw));
      return parsed.success ? parsed.data : {};
    } catch {
      return {};
    }
  }

  private async loadLookup(): Promise<Record<string, string>> {
    const lookupPath = path.join(this.cacheDir, LOOKUP_FILE);
    if (!existsSync(lookupPath)) return {};
    try {
      const raw = await readFile(lookupPath, "utf-8");
      const parsed = JSON.parse(raw);
      if (typeof parsed === "object" && parsed !== null)
        return parsed as Record<string, string>;
      return {};
    } catch {
      return {};
    }
  }

  private async saveManifest(manifest: ArtifactManifest): Promise<void> {
    const manifestPath = path.join(this.cacheDir, MANIFEST_FILE);
    await writeFileAtomic(
      manifestPath,
      JSON.stringify(manifest, null, 2) + "\n",
    );
  }
}
